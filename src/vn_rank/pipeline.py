"""Research pipeline commands (I/O layer): train, backtest.

Each function loads its inputs through :mod:`vn_rank.data.storage`, delegates to the pure
library modules, writes reports, and returns a process exit code. ``cli.py`` only parses
arguments and dispatches here, so both files stay small.
"""

from __future__ import annotations

import dataclasses
import hashlib
import json
import logging
import subprocess

import pandas as pd

from vn_rank.backtest import runner
from vn_rank.backtest.costs import cost_model
from vn_rank.backtest.engine import EngineSettings, Market
from vn_rank.config import Config, config_to_dict
from vn_rank.data import storage
from vn_rank.evaluation.bootstrap import BootstrapSettings
from vn_rank.evaluation.ic import SignalSettings
from vn_rank.features import builder, labels
from vn_rank.utils import report_paths
from vn_rank.utils.logging import MlflowFoldLogger
from vn_rank.utils.seeds import set_global_seed
from vn_rank.validation import splits, walk_forward

PANEL_FILE = "panel.parquet"
PREDICTIONS_FILE = "predictions.parquet"
RESULTS_STEM = "signal_results"
BACKTEST_STEM = "backtest_results"
EQUITY_FIGURE = "equity_curves.png"
DAILY_RETURNS_FILE = "backtest_daily.parquet"
DIGITS = 4
EXPERIMENT_NAME = "walk_forward"
TRIPWIRE_EXIT_CODE = 2
logger = logging.getLogger(__name__)


@dataclasses.dataclass(frozen=True)
class Prices:
    """Raw prices, the VNINDEX calendar and closes, and today's exchange per symbol."""

    raw: pd.DataFrame
    calendar: pd.DatetimeIndex
    index_close: pd.Series
    exchange: pd.Series


def load_prices(config: Config, before: pd.Timestamp | None) -> Prices:
    """Load the raw snapshot, keeping only sessions before ``before`` when given."""
    raw_dir = config.paths.raw_dir
    raw = storage.load_ohlcv_panel(raw_dir)
    index = storage.read_parquet(storage.index_path(raw_dir, config.data.index_symbol))
    if before is not None:
        raw, index = raw.loc[raw["date"] < before], index.loc[index["date"] < before]
    index = index.sort_values("date")
    symbols = storage.read_parquet(raw_dir / storage.SYMBOLS_FILE)
    return Prices(
        raw=raw,
        calendar=pd.DatetimeIndex(index["date"]),
        index_close=index.set_index("date")["close"],
        exchange=symbols.set_index("symbol")["exchange"],
    )


def run_info(config: Config) -> dict[str, str]:
    """SHA-256 of the canonical config and the current git commit (for provenance)."""
    canonical = json.dumps(config_to_dict(config), sort_keys=True, default=str)
    git = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True, check=False)
    return {
        "config_sha256": hashlib.sha256(canonical.encode()).hexdigest(),
        "git_commit": git.stdout.strip() or "unknown",
    }


def provenance(info: dict[str, str], command: str) -> str:
    """One report line naming the command, commit, and config hash."""
    return (
        f"Generated by `vn-rank {command}` at commit `{info['git_commit'][:12]}`;"
        f" config SHA-256 `{info['config_sha256'][:12]}`."
    )


def train(config: Config) -> int:
    """Walk-forward tuning, fitting, and scoring of every model; writes signal results."""
    set_global_seed(config.project.seed)
    panel = storage.read_parquet(config.paths.processed_dir / PANEL_FILE)
    samples = splits.development_samples(panel, config.validation)
    info = run_info(config)
    with MlflowFoldLogger(config.paths.mlruns_dir, EXPERIMENT_NAME, info) as log_fold:
        specs = walk_forward.model_specs(config)
        predictions = walk_forward.run_walk_forward(samples, specs, config, log_fold)
    storage.write_parquet(predictions, config.paths.processed_dir / PREDICTIONS_FILE)
    signal = SignalSettings(config.label.horizon_days, config.evaluation.n_quantiles)
    table = walk_forward.results_table(predictions, signal)
    reports = report_paths.section(config.paths.reports_dir, report_paths.WALK_FORWARD)
    storage.write_text(table.to_csv(index=False), reports / f"{RESULTS_STEM}.csv")
    header = [
        "# Signal-level results on walk-forward folds",
        "",
        f"{provenance(info, 'train')} Optuna configurations tried: {log_fold.n_trials}.",
    ]
    text = walk_forward.render_results_markdown(table, header, DIGITS)
    storage.write_text(text, reports / f"{RESULTS_STEM}.md")
    logger.info("Results:\n%s", text)
    evaluation = config.evaluation
    breaches = walk_forward.tripwire_breaches(
        table, evaluation.tripwire_mean_ic, evaluation.tripwire_fold_ic
    )
    if breaches:
        logger.error("Leakage tripwire breached; investigate before reporting: %s", breaches)
        return TRIPWIRE_EXIT_CODE
    return 0


def backtest_settings(config: Config) -> runner.BacktestSettings:
    """Engine, portfolio, and bootstrap settings from the configuration."""
    bt, evaluation = config.backtest, config.evaluation
    if bt.max_position_fraction_of_adv is None:
        raise ValueError("backtest.max_position_fraction_of_adv must be set")
    engine = EngineSettings(
        cost_model(bt.costs),
        bt.max_position_fraction_of_adv,
        bt.portfolio_value_vnd,
        bt.limit_hit_margin,
    )
    boot = BootstrapSettings(
        evaluation.bootstrap_block_days,
        evaluation.bootstrap_resamples,
        evaluation.confidence_level,
        config.project.seed,
    )
    return runner.BacktestSettings(
        engine,
        bt.top_quantile,
        config.label.horizon_days,
        evaluation.trading_days_per_year,
        boot,
        bt.turnover_band,
    )


def market_data(config: Config, prices: Prices) -> Market:
    """Market data for the engine from the calendar-aligned price frames."""
    frames = builder.align_to_calendar(builder.repair_ohlc(prices.raw), prices.calendar)
    bt = config.backtest
    return runner.build_market(frames, prices.exchange, bt.price_limits, bt.position_cap_adv_window)


def backtest(config: Config) -> int:
    """Backtest every model's walk-forward predictions against the benchmarks."""
    prices = load_prices(config, pd.Timestamp(config.validation.lockbox_start))
    predictions = storage.read_parquet(config.paths.processed_dir / PREDICTIONS_FILE)
    entry_dates = labels.label_entry_dates(prices.calendar, config.label)
    market = market_data(config, prices)
    report = runner.backtest_all(
        predictions, entry_dates, (market, prices.index_close), backtest_settings(config)
    )
    reports = report_paths.section(config.paths.reports_dir, report_paths.WALK_FORWARD)
    info = run_info(config)
    storage.write_text(report.summary.to_csv(), reports / f"{BACKTEST_STEM}.csv")
    storage.write_text(report.yearly.to_csv(), reports / f"{BACKTEST_STEM}_yearly.csv")
    storage.write_parquet(
        pd.DataFrame(report.curves).rename_axis("date").reset_index(),
        config.paths.processed_dir / DAILY_RETURNS_FILE,
    )
    header = [
        "# Walk-forward backtest (long-only top decile, net of costs)",
        "",
        provenance(info, "backtest"),
    ]
    text = runner.render_backtest_markdown(report, header, DIGITS)
    storage.write_text(text, reports / f"{BACKTEST_STEM}.md")
    figure = runner.plot_equity(
        report.curves, "Walk-forward test blocks 2022-01 to 2025-09, net of costs"
    )
    storage.save_figure(figure, reports / EQUITY_FIGURE, config.project.figure_dpi)
    logger.info("Backtest:\n%s", text)
    return 0
